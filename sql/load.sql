CREATE DATABASE IF NOT EXISTS lab;

CREATE EXTERNAL TABLE IF NOT EXISTS lab.sales (
    sale_id INT,
    product STRING,
    amount DECIMAL(10, 2)
)
PARTITIONED BY (sale_date STRING)
ROW FORMAT DELIMITED
FIELDS TERMINATED BY ','
STORED AS TEXTFILE
LOCATION '/opt/hive/data/warehouse/sales';

LOAD DATA LOCAL INPATH '/data/2026-10-01.csv'
OVERWRITE INTO TABLE lab.sales PARTITION (sale_date='2026-10-01');

